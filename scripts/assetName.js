// Каноническое преобразование пути внутри игровой папки в имя ассета GitHub Releases.
//
// GitHub Releases не поддерживает "/" в именах ассетов, поэтому разделитель — "__".
// Пробелы и прочие небезопасные символы заменяем на "_" (GitHub сам портит пробелы),
// чтобы имя ассета в релизе гарантированно совпадало с тем, что прописано в манифесте.
//
// Этот модуль используется И ген-скриптом манифеста, И скриптом публикации,
// чтобы URL в манифесте всегда точно соответствовал имени загружаемого ассета.
//
//   "mods/CustomNPCs-1.16.5.20220515.jar"      → "mods__CustomNPCs-1.16.5.20220515.jar"
//   "versions/Forge 1.16.5/Forge 1.16.5.json"  → "versions__Forge_1.16.5__Forge_1.16.5.json"

function assetName(rel) {
  return rel
    .split("/")
    .map((seg) => seg.replace(/[^A-Za-z0-9._-]/g, "_"))
    .join("__");
}

module.exports = { assetName };
